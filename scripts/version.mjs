// Writes src/version.ts from package.json, so bundles that include the
// library (such as the GitHub Action) report the right version.
import { readFile, writeFile } from 'node:fs/promises'
const { version } = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'))
await writeFile(new URL('../src/version.ts', import.meta.url), `// Generated by scripts/version.mjs from package.json.\nexport const VERSION = '${version}'\n`)
